"""Rebuild native Slint curves from the bundled Telegram 3x alpha masks.

Optional authoring tools, never needed to build or run Relay:
    pip install Pillow==13.0.0 potracer==0.0.4 numpy==2.5.4
    python tools/vectorize_icons.py
"""

from pathlib import Path

from PIL import Image
from potrace import Bitmap

ROOT = Path(__file__).resolve().parents[1]
ICONS = ROOT / "ui" / "icons"
NAMES = (
    "advanced back call channel chat-settings chats clip close edit-folders folder "
    "groups_create language maximize menu mic minimize moon more notifications panel "
    "personal phone power privacy profile read saved search send sent settings smile window-close"
).split()


def trace(name):
    image = Image.open(ICONS / f"{name}.png")
    alpha = image.getchannel("A") if "A" in image.getbands() else image.convert("L")
    width, height = alpha.size
    # Interpolate the coverage mask before tracing its 50% contour. This retains
    # subpixel edge positions; tracing the original binary pixel grid would
    # bake its staircase back into the vector. Coordinates remain logical px.
    factor = 4
    coverage = alpha.resize((width * factor, height * factor), Image.Resampling.LANCZOS)
    mask = Image.eval(coverage, lambda value: 255 - value)
    curves = Bitmap(mask, blacklevel=0.5).trace(
        turdsize=0, alphamax=1.0, opticurve=True, opttolerance=0.8,
    )
    scale = 1 / (3 * factor)

    def point(p):
        return f"{p.x * scale:.4f} {p.y * scale:.4f}"

    commands = []
    for curve in curves:
        commands.append("M" + point(curve.start_point))
        for segment in curve.segments:
            if segment.is_corner:
                commands.append("L" + point(segment.c) + "L" + point(segment.end_point))
            else:
                commands.append("C" + point(segment.c1) + " " + point(segment.c2) + " " + point(segment.end_point))
        commands.append("Z")
    return width / 3, height / 3, "".join(commands)


def main():
    lines = [
        "// Generated by tools/vectorize_icons.py. Telegram-derived contours; see licenses/NOTICE.md.",
        "// Paths are filled directly by Skia at the current display scale.",
        "struct IconData { width: float, height: float, commands: string }",
        "global IconPaths {",
        "    public pure function lookup(name: string) -> IconData {",
    ]
    for name in NAMES:
        width, height, commands = trace(name)
        lines.append(f'        if name == "{name}" {{ return {{ width: {width:g}, height: {height:g}, commands: "{commands}" }}; }}')
    lines.extend([
        '        return { width: 0, height: 0, commands: "" };',
        "    }", "}", "",
        "export component VectorIcon inherits Path {",
        "    in property <string> name;",
        "    in property <color> tint;",
        "    private property <IconData> data: IconPaths.lookup(name);",
        "    out property <length> natural-width: data.width * 1px;",
        "    out property <length> natural-height: data.height * 1px;",
        "    width: natural-width;", "    height: natural-height;",
        "    viewbox-width: data.width;", "    viewbox-height: data.height;",
        "    fit: fill;", "    anti-alias: true;",
        "    fill: tint;", "    fill-rule: evenodd;", "    commands: data.commands;", "}",
    ])
    (ICONS / "vector-icons.slint").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
